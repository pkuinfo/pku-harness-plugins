// Embed the official plugin documents (plugins/<id>/PLUGIN.md + the files it names) into
// plugins/documents.generated.ts, which the app ships as bundled plugins. Run after changing a
// document; CI checks the file is up to date (`bun scripts/bundle-docs.ts --check`).
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

import { loadDocument } from '../packages/sdk/src';

const root = new URL('../plugins/', import.meta.url).pathname;
const out = join(root, 'documents.generated.ts');
const docs: Record<string, { link: string; files: Record<string, string> }> = {};
for (const dir of readdirSync(root, { withFileTypes: true })) {
  if (!dir.isDirectory() || !existsSync(join(root, dir.name, 'PLUGIN.md'))) continue;
  const doc = await loadDocument(async (p) => readFileSync(join(root, dir.name, p), 'utf8'));
  docs[doc.manifest.id] = { link: `https://github.com/pkuinfo/pku-harness-plugins/tree/main/plugins/${dir.name}`, files: doc.files };
}
const text = `// Generated by scripts/bundle-docs.ts from plugins/*/PLUGIN.md. Do not edit.
export const bundledDocuments: Record<string, { link: string; files: Record<string, string> }> = ${JSON.stringify(docs, null, 2)};
`;
if (process.argv.includes('--check')) {
  if (!existsSync(out) || readFileSync(out, 'utf8') !== text) {
    console.error('plugins/documents.generated.ts is out of date: run bun scripts/bundle-docs.ts');
    process.exit(1);
  }
  console.log(`bundled documents ok: ${Object.keys(docs).join(', ')}`);
} else {
  writeFileSync(out, text);
  console.log(`wrote ${Object.keys(docs).length} documents: ${Object.keys(docs).join(', ')}`);
}
